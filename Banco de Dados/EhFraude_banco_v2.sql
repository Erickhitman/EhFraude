-- usuario
DROP POLICY IF EXISTS usuario_select ON public.usuario;
CREATE POLICY usuario_select ON public.usuario FOR SELECT TO authenticated
    USING (id_usuario = auth.uid() OR public.eh_admin());
DROP POLICY IF EXISTS usuario_insert ON public.usuario;
CREATE POLICY usuario_insert ON public.usuario FOR INSERT TO authenticated
    WITH CHECK (id_usuario = auth.uid() AND perfil = 'USUARIO' AND xp_total = 0 AND nivel_atual = 1);
DROP POLICY IF EXISTS usuario_update ON public.usuario;
CREATE POLICY usuario_update ON public.usuario FOR UPDATE TO authenticated
    USING (id_usuario = auth.uid()) WITH CHECK (id_usuario = auth.uid());
-- O usuário só pode editar nome e e-mail; perfil, XP e nível ficam com o servidor.
