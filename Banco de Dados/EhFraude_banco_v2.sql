-- usuario: o id é o mesmo do Supabase Auth. Login e senha ficam no Auth.
CREATE TABLE IF NOT EXISTS public.usuario (
    id_usuario    UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    nome          VARCHAR(150) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    perfil        VARCHAR(20)  NOT NULL DEFAULT 'USUARIO',
    xp_total      INTEGER      NOT NULL DEFAULT 0,
    nivel_atual   INTEGER      NOT NULL DEFAULT 1,
    data_cadastro TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT usuario_email_uk     UNIQUE (email),
    CONSTRAINT usuario_nome_ck      CHECK (char_length(btrim(nome)) >= 2),
    CONSTRAINT usuario_email_ck     CHECK (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT usuario_perfil_ck    CHECK (perfil IN ('USUARIO', 'ADMINISTRADOR')),
    CONSTRAINT usuario_xp_ck        CHECK (xp_total >= 0),
    CONSTRAINT usuario_nivel_ck     CHECK (nivel_atual >= 1)
);

CREATE TABLE IF NOT EXISTS public.consentimento (
    id_consentimento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario       UUID         NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
    finalidade       VARCHAR(80)  NOT NULL,
    concedido        BOOLEAN      NOT NULL,
    versao_termo     VARCHAR(20)  NOT NULL,
    data_registro    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.solicitacao_exclusao (
    id_solicitacao   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario       UUID         NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
    status           VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    data_solicitacao TIMESTAMPTZ  NOT NULL DEFAULT now(),
    data_conclusao   TIMESTAMPTZ,
    CONSTRAINT solicitacao_status_ck    CHECK (status IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDA')),
    CONSTRAINT solicitacao_conclusao_ck CHECK (status <> 'CONCLUIDA' OR data_conclusao IS NOT NULL),
    CONSTRAINT solicitacao_datas_ck     CHECK (data_conclusao IS NULL OR data_conclusao >= data_solicitacao)
);

CREATE TABLE IF NOT EXISTS public.conquista (
    id_conquista  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(80) NOT NULL,
    descricao     TEXT        NOT NULL,
    xp_necessario INTEGER     NOT NULL,
    CONSTRAINT conquista_nome_uk UNIQUE (nome),
    CONSTRAINT conquista_xp_ck   CHECK (xp_necessario >= 0)
);

CREATE TABLE IF NOT EXISTS public.tipo_golpe (
    id_tipo_golpe INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(80) NOT NULL,
    descricao     TEXT,
    CONSTRAINT tipo_golpe_nome_uk UNIQUE (nome)
);

CREATE TABLE IF NOT EXISTS public.usuario_conquista (
    id_usuario    UUID        NOT NULL REFERENCES public.usuario(id_usuario)      ON DELETE CASCADE,
    id_conquista  INTEGER     NOT NULL REFERENCES public.conquista(id_conquista)  ON DELETE RESTRICT,
    data_obtencao TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id_usuario, id_conquista)
);

CREATE TABLE IF NOT EXISTS public.golpe_recente (
    id_golpe_recente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_publicador    UUID    REFERENCES public.usuario(id_usuario)       ON DELETE SET NULL,
    id_tipo_golpe    INTEGER REFERENCES public.tipo_golpe(id_tipo_golpe) ON DELETE SET NULL,
    titulo           VARCHAR(150) NOT NULL,
    descricao        TEXT         NOT NULL,
    data_publicacao  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ativo            BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.desafio (
    id_desafio          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_criador          UUID    REFERENCES public.usuario(id_usuario)       ON DELETE SET NULL,
    id_tipo_golpe       INTEGER REFERENCES public.tipo_golpe(id_tipo_golpe) ON DELETE SET NULL,
    titulo              VARCHAR(150) NOT NULL,
    conteudo            TEXT         NOT NULL,
    alternativa_a       VARCHAR(300) NOT NULL,
    alternativa_b       VARCHAR(300) NOT NULL,
    alternativa_c       VARCHAR(300) NOT NULL,
    alternativa_d       VARCHAR(300) NOT NULL,
    alternativa_correta VARCHAR(1)   NOT NULL,
    nivel               VARCHAR(20)  NOT NULL,
    origem              VARCHAR(20)  NOT NULL,
    explicacao_gabarito TEXT         NOT NULL,
    pontuacao_maxima    INTEGER      NOT NULL,
    ativo               BOOLEAN      NOT NULL DEFAULT TRUE,
    data_criacao        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT desafio_correta_ck  CHECK (alternativa_correta IN ('A', 'B', 'C', 'D')),
    CONSTRAINT desafio_nivel_ck    CHECK (nivel IN ('FACIL', 'MEDIO', 'DIFICIL')),
    CONSTRAINT desafio_origem_ck   CHECK (origem IN ('IA', 'ADMIN')),
    CONSTRAINT desafio_pontos_ck   CHECK (pontuacao_maxima BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS public.resposta_desafio (
    id_resposta          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario           UUID       NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
    id_desafio           INTEGER    NOT NULL REFERENCES public.desafio(id_desafio) ON DELETE RESTRICT,
    alternativa_escolhida VARCHAR(1) NOT NULL,
    acertou              BOOLEAN    NOT NULL,
    pontos_obtidos       INTEGER    NOT NULL,
    feedback             TEXT,
    data_resposta        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT resposta_alternativa_ck CHECK (alternativa_escolhida IN ('A', 'B', 'C', 'D')),
    CONSTRAINT resposta_pontos_ck      CHECK (pontos_obtidos >= 0)
);

-- analise: pode ser feita sem login (id_usuario nulo). O id é gerado pela aplicação.
CREATE TABLE IF NOT EXISTS public.analise (
    id_analise          VARCHAR(150) PRIMARY KEY,
    id_usuario          UUID    REFERENCES public.usuario(id_usuario)       ON DELETE CASCADE,
    id_tipo_golpe       INTEGER REFERENCES public.tipo_golpe(id_tipo_golpe) ON DELETE SET NULL,
    tipo_conteudo       VARCHAR(20)  NOT NULL,
    origem              VARCHAR(20)  NOT NULL,
    conteudo_original   TEXT         NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    nivel_risco         VARCHAR(20),
    probabilidade_golpe NUMERIC(5,2),
    explicacao          TEXT,
    recomendacao        TEXT,
    tempo_resposta_ms   INTEGER,
    salvar_historico    BOOLEAN      NOT NULL DEFAULT FALSE,
    data_analise        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT analise_tipo_ck     CHECK (tipo_conteudo IN ('LINK', 'TEXTO', 'LINK_E_TEXTO')),
    CONSTRAINT analise_origem_ck   CHECK (origem IN ('SITE', 'EXTENSAO')),
    CONSTRAINT analise_status_ck   CHECK (status IN ('PENDENTE', 'CONCLUIDA', 'FALHA')),
    CONSTRAINT analise_nivel_ck    CHECK (nivel_risco IS NULL OR nivel_risco IN ('SEGURO', 'ATENCAO', 'CUIDADO')),
    CONSTRAINT analise_prob_ck     CHECK (probabilidade_golpe IS NULL OR probabilidade_golpe BETWEEN 0 AND 100),
    CONSTRAINT analise_tempo_ck    CHECK (tempo_resposta_ms IS NULL OR tempo_resposta_ms >= 0),
    CONSTRAINT analise_concluida_ck CHECK (
        status <> 'CONCLUIDA'
        OR (nivel_risco IS NOT NULL AND probabilidade_golpe IS NOT NULL
            AND explicacao IS NOT NULL AND recomendacao IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS public.avaliacao_analise (
    id_avaliacao    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_analise      VARCHAR(150) NOT NULL REFERENCES public.analise(id_analise) ON DELETE CASCADE,
