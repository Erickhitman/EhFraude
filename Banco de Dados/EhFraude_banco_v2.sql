-- ---------------------------------------------------------------------
-- 3. REGRAS ENTRE TABELAS (triggers)
-- resposta_desafio: acertou deve bater com o gabarito do desafio e os pontos
-- ficam entre 0 e desafio.pontuacao_maxima (0 quando errou).
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.valida_resposta_desafio()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_correta VARCHAR(1);
    v_max     INTEGER;
BEGIN
    SELECT alternativa_correta, pontuacao_maxima INTO v_correta, v_max
    FROM public.desafio WHERE id_desafio = NEW.id_desafio;

    IF NEW.acertou <> (NEW.alternativa_escolhida = v_correta) THEN
        RAISE EXCEPTION 'acertou não confere com o gabarito do desafio %', NEW.id_desafio;
    END IF;
    IF NEW.pontos_obtidos > v_max THEN
        RAISE EXCEPTION 'pontos_obtidos (%) maior que a pontuação máxima (%)', NEW.pontos_obtidos, v_max;
    END IF;
    IF NOT NEW.acertou AND NEW.pontos_obtidos <> 0 THEN
        RAISE EXCEPTION 'pontos_obtidos deve ser 0 quando o usuário errou';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_valida_resposta_desafio ON public.resposta_desafio;
CREATE TRIGGER trg_valida_resposta_desafio
    BEFORE INSERT OR UPDATE ON public.resposta_desafio
    FOR EACH ROW EXECUTE FUNCTION public.valida_resposta_desafio();

-- desafio: o criador é obrigatório quando origem = ADMIN. A regra vale na
-- criação; depois, se a conta do administrador for apagada, id_criador vira
-- nulo (ON DELETE SET NULL) e o desafio continua existindo.
CREATE OR REPLACE FUNCTION public.valida_criador_desafio()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.origem = 'ADMIN' AND NEW.id_criador IS NULL THEN
        RAISE EXCEPTION 'desafio de origem ADMIN exige id_criador';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_valida_criador_desafio ON public.desafio;
CREATE TRIGGER trg_valida_criador_desafio
    BEFORE INSERT ON public.desafio
    FOR EACH ROW EXECUTE FUNCTION public.valida_criador_desafio();

-- ---------------------------------------------------------------------
-- 4. ROW LEVEL SECURITY (RLS)
-- Regras:
--  - Cada usuário lê e altera apenas os próprios dados.
--  - Catálogos (tipo_golpe, conquista, golpe_recente) são de leitura pública.
--  - O gabarito do desafio não é exposto: o front lê a view desafio_publico.
--  - O administrador altera o catálogo. Pontuação, análises e demais
--    gravações do sistema são feitas pelo servidor (service_role, que ignora RLS).
-- ---------------------------------------------------------------------

-- Função auxiliar: o usuário logado é administrador?
CREATE OR REPLACE FUNCTION public.eh_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.usuario
        WHERE id_usuario = auth.uid() AND perfil = 'ADMINISTRADOR'
    );
$$;

ALTER TABLE public.usuario              ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tipo_golpe           ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conquista            ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.desafio              ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analise              ENABLE ROW LEVEL SECURITY;
